valor = input('Digite um valor: ')
print('O tipo do valor digitado é {}'.format(type(valor)))
print('O valor é alfanumerico ? {}'.format(valor.isalnum()))
print('O valor é alfabetico ? {}'.format(valor.isalpha()))
print('O valor é numerico ? {}'.format(valor.isnumeric()))
print('O valor é decimal ? {}'.format(valor.isdecimal()))
print('O valor está minusculo ? {}'.format(valor.islower()))
print('O valor está maiusculo ? {}'.format(valor.isupper()))
print('O valor só tem espaços ? {}'.format(valor.isspace()))
print('O valor está catilatilizado ? {}'.format(valor.istitle()))
